void Speaker::InitializeCst816DTouchPad() {
  ESP_LOGI(TAG, "Init Cst816D");
  cst816d_ = new Cst816d(i2c_bus_, 0x15);

  // 创建定时器，10ms 间隔
  esp_timer_create_args_t timer_args = {
      .callback = touchpad_timer_callback,
      .arg = NULL,
      .dispatch_method = ESP_TIMER_TASK,
      .name = "touchpad_timer",
      .skip_unhandled_events = true,
  };

  ESP_ERROR_CHECK(esp_timer_create(&timer_args, &touchpad_timer_));
  ESP_ERROR_CHECK(esp_timer_start_periodic(touchpad_timer_, 10 * 1000)); // 10ms = 10000us
}

void Speaker::touchpad_timer_callback(void* arg) {
    Speaker *board = Speaker::GetInstance();
    auto touchpad = board->GetTouchpad();
    static bool was_touched = false;
    static int64_t touch_start_time = 0;
    const int64_t TOUCH_THRESHOLD_MS = 500;  // 触摸时长阈值，超过500ms视为长按

    touchpad->UpdateTouchPoint();
    auto touch_point = touchpad->GetTouchPoint();

    // 检测触摸开始
    if (touch_point.num > 0 && !was_touched) {
        was_touched = true;
        touch_start_time = esp_timer_get_time() / 1000; // 转换为毫秒
    }
    // 检测触摸释放
    else if (touch_point.num == 0 && was_touched) {
        was_touched = false;
        int64_t touch_duration = (esp_timer_get_time() / 1000) - touch_start_time;

        // 只有短触才触发
        if (touch_duration < TOUCH_THRESHOLD_MS) {
            // auto& app = Application::GetInstance();
            // if (app.GetDeviceState() == kDeviceStateStarting &&
            //     !WifiStation::GetInstance().IsConnected()) {
            //     board.ResetWifiConfiguration();
            // }
            // app.ToggleChatState();
        }
    }
}

