Speaker::Speaker()
{
  gpio_set_direction(TP_PIN_NUM_TP_INT, GPIO_MODE_INPUT);
  int level = gpio_get_level(TP_PIN_NUM_TP_INT);
  if (level == 1) {
    InitializeCodecI2c_Touch();
    InitializeCst816DTouchPad();
  } else {
    log_w("TouchPad not found!");
  }

  InitializeCodecI2c();
}

